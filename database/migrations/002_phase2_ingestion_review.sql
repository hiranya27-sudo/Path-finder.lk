BEGIN;

ALTER TABLE jobs
    ADD COLUMN IF NOT EXISTS is_fixture BOOLEAN NOT NULL DEFAULT FALSE;

CREATE OR REPLACE FUNCTION refresh_skill_demand()
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    active_job_count INTEGER;
BEGIN
    SELECT count(*)::INTEGER
      INTO active_job_count
      FROM jobs
     WHERE NOT is_fixture
       AND (expires_at IS NULL OR expires_at > now());

    INSERT INTO skill_demand (
        skill_id,
        job_count,
        total_jobs,
        demand_score,
        updated_at
    )
    SELECT
        s.skill_id,
        count(DISTINCT j.job_id)::INTEGER,
        active_job_count,
        CASE
            WHEN active_job_count = 0 THEN 0
            ELSE count(DISTINCT j.job_id)::NUMERIC / active_job_count
        END,
        now()
    FROM skills AS s
    LEFT JOIN job_skills AS js ON js.skill_id = s.skill_id
    LEFT JOIN jobs AS j
        ON j.job_id = js.job_id
       AND NOT j.is_fixture
       AND (j.expires_at IS NULL OR j.expires_at > now())
    GROUP BY s.skill_id
    ON CONFLICT (skill_id) DO UPDATE
       SET job_count = EXCLUDED.job_count,
           total_jobs = EXCLUDED.total_jobs,
           demand_score = EXCLUDED.demand_score,
           updated_at = EXCLUDED.updated_at;
END;
$$;

CREATE TABLE IF NOT EXISTS ingestion_runs (
    ingestion_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'running',
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    jobs_seen INTEGER NOT NULL DEFAULT 0,
    jobs_inserted INTEGER NOT NULL DEFAULT 0,
    jobs_updated INTEGER NOT NULL DEFAULT 0,
    error_code TEXT,
    CONSTRAINT ingestion_runs_source_nonempty
        CHECK (length(btrim(source)) > 0),
    CONSTRAINT ingestion_runs_status_valid
        CHECK (status IN ('running', 'succeeded', 'failed')),
    CONSTRAINT ingestion_runs_counts_nonnegative
        CHECK (
            jobs_seen >= 0
            AND jobs_inserted >= 0
            AND jobs_updated >= 0
        ),
    CONSTRAINT ingestion_runs_completion_consistent
        CHECK (
            (status = 'running' AND completed_at IS NULL)
            OR (status <> 'running' AND completed_at IS NOT NULL)
        )
);

CREATE INDEX IF NOT EXISTS ingestion_runs_source_started_idx
    ON ingestion_runs (source, started_at DESC);

CREATE TABLE IF NOT EXISTS skill_candidate_observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL
        REFERENCES skill_candidates (candidate_id) ON DELETE CASCADE,
    source_type TEXT NOT NULL,
    source_event_key TEXT NOT NULL,
    job_id BIGINT
        REFERENCES jobs (job_id) ON DELETE CASCADE,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT skill_candidate_observations_source_valid
        CHECK (source_type IN ('job', 'resume', 'github')),
    CONSTRAINT skill_candidate_observations_event_key_nonempty
        CHECK (length(btrim(source_event_key)) > 0),
    CONSTRAINT skill_candidate_observations_job_source_consistent
        CHECK (
            (source_type = 'job' AND job_id IS NOT NULL)
            OR (source_type <> 'job' AND job_id IS NULL)
        ),
    CONSTRAINT skill_candidate_observations_unique_event
        UNIQUE (candidate_id, source_type, source_event_key)
);

CREATE INDEX IF NOT EXISTS skill_candidate_observations_recent_idx
    ON skill_candidate_observations (candidate_id, observed_at DESC);

CREATE INDEX IF NOT EXISTS skill_candidate_observations_job_idx
    ON skill_candidate_observations (job_id)
    WHERE job_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS skill_candidate_observations_job_event_uidx
    ON skill_candidate_observations (candidate_id, job_id)
    WHERE job_id IS NOT NULL;

CREATE OR REPLACE VIEW skill_candidate_review_queue AS
SELECT
    candidate.candidate_id,
    candidate.raw_term,
    candidate.status,
    candidate.canonical_skill_id,
    candidate.first_seen_at,
    candidate.last_seen_at,
    count(observation.observation_id) FILTER (
        WHERE observation.observed_at >= now() - INTERVAL '30 days'
    )::INTEGER AS frequency_30d,
    count(observation.observation_id) FILTER (
        WHERE observation.observed_at >= now() - INTERVAL '30 days'
    ) >= 5 AS meets_review_threshold
FROM skill_candidates AS candidate
LEFT JOIN skill_candidate_observations AS observation
    ON observation.candidate_id = candidate.candidate_id
GROUP BY
    candidate.candidate_id,
    candidate.raw_term,
    candidate.status,
    candidate.canonical_skill_id,
    candidate.first_seen_at,
    candidate.last_seen_at;

CREATE TABLE IF NOT EXISTS skill_candidate_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL
        REFERENCES skill_candidates (candidate_id) ON DELETE CASCADE,
    action TEXT NOT NULL,
    reviewer_ref TEXT NOT NULL,
    target_skill_id BIGINT
        REFERENCES skills (skill_id) ON DELETE RESTRICT,
    notes TEXT,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT skill_candidate_reviews_action_valid
        CHECK (action IN ('approved', 'rejected', 'merged')),
    CONSTRAINT skill_candidate_reviews_reviewer_nonempty
        CHECK (length(btrim(reviewer_ref)) > 0),
    CONSTRAINT skill_candidate_reviews_target_consistent
        CHECK (
            (action IN ('approved', 'merged') AND target_skill_id IS NOT NULL)
            OR (action = 'rejected' AND target_skill_id IS NULL)
        )
);

CREATE INDEX IF NOT EXISTS skill_candidate_reviews_candidate_decided_idx
    ON skill_candidate_reviews (candidate_id, decided_at DESC);

CREATE TABLE IF NOT EXISTS student_data_consent_events (
    consent_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES student_profiles (user_id) ON DELETE CASCADE,
    source_type TEXT NOT NULL,
    action TEXT NOT NULL,
    policy_version TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT student_data_consent_source_valid
        CHECK (source_type IN ('resume', 'github')),
    CONSTRAINT student_data_consent_action_valid
        CHECK (action IN ('granted', 'revoked')),
    CONSTRAINT student_data_consent_policy_nonempty
        CHECK (length(btrim(policy_version)) > 0)
);

CREATE INDEX IF NOT EXISTS student_data_consent_latest_idx
    ON student_data_consent_events (user_id, source_type, recorded_at DESC);

COMMIT;
