BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS skills (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name TEXT NOT NULL UNIQUE,
    domain_cluster TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT skills_canonical_name_nonempty
        CHECK (length(btrim(canonical_name)) > 0),
    CONSTRAINT skills_domain_cluster_nonempty
        CHECK (length(btrim(domain_cluster)) > 0)
);

CREATE TABLE IF NOT EXISTS skill_aliases (
    alias_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_term TEXT NOT NULL,
    skill_id BIGINT NOT NULL
        REFERENCES skills (skill_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT skill_aliases_raw_term_nonempty
        CHECK (length(btrim(raw_term)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS skill_aliases_raw_term_lower_uidx
    ON skill_aliases (lower(raw_term));

CREATE TABLE IF NOT EXISTS skill_candidates (
    candidate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_term TEXT NOT NULL,
    frequency_count INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'pending',
    canonical_skill_id BIGINT
        REFERENCES skills (skill_id) ON DELETE SET NULL,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    CONSTRAINT skill_candidates_raw_term_nonempty
        CHECK (length(btrim(raw_term)) > 0),
    CONSTRAINT skill_candidates_frequency_positive
        CHECK (frequency_count > 0),
    CONSTRAINT skill_candidates_status_valid
        CHECK (status IN ('pending', 'approved', 'rejected', 'merged')),
    CONSTRAINT skill_candidates_reviewed_status_consistent
        CHECK (
            (status = 'pending' AND reviewed_at IS NULL)
            OR (status <> 'pending' AND reviewed_at IS NOT NULL)
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS skill_candidates_raw_term_lower_uidx
    ON skill_candidates (lower(raw_term));

CREATE TABLE IF NOT EXISTS job_roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL,
    role_vector vector(384),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT job_roles_title_nonempty CHECK (length(btrim(title)) > 0),
    CONSTRAINT job_roles_description_nonempty
        CHECK (length(btrim(description)) > 0)
);

CREATE TABLE IF NOT EXISTS role_skills (
    role_id BIGINT NOT NULL
        REFERENCES job_roles (role_id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL
        REFERENCES skills (skill_id) ON DELETE RESTRICT,
    required_level SMALLINT NOT NULL,
    importance_weight NUMERIC(6, 4) NOT NULL DEFAULT 1.0,
    PRIMARY KEY (role_id, skill_id),
    CONSTRAINT role_skills_required_level_valid
        CHECK (required_level BETWEEN 1 AND 5),
    CONSTRAINT role_skills_importance_weight_positive
        CHECK (importance_weight > 0)
);

CREATE TABLE IF NOT EXISTS jobs (
    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    source_job_id TEXT,
    source_url TEXT,
    title TEXT NOT NULL,
    company TEXT,
    location TEXT,
    experience TEXT,
    description TEXT NOT NULL,
    posted_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    collected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    embedding vector(384),
    CONSTRAINT jobs_source_nonempty CHECK (length(btrim(source)) > 0),
    CONSTRAINT jobs_title_nonempty CHECK (length(btrim(title)) > 0),
    CONSTRAINT jobs_description_nonempty
        CHECK (length(btrim(description)) > 0),
    CONSTRAINT jobs_source_identifier_unique UNIQUE (source, source_job_id)
);

CREATE INDEX IF NOT EXISTS jobs_collected_at_idx
    ON jobs (collected_at DESC);

CREATE INDEX IF NOT EXISTS jobs_expires_at_idx
    ON jobs (expires_at);

CREATE TABLE IF NOT EXISTS job_skills (
    job_id BIGINT NOT NULL
        REFERENCES jobs (job_id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL
        REFERENCES skills (skill_id) ON DELETE RESTRICT,
    evidence TEXT,
    extraction_method TEXT NOT NULL,
    confidence NUMERIC(5, 4),
    PRIMARY KEY (job_id, skill_id),
    CONSTRAINT job_skills_extraction_method_nonempty
        CHECK (length(btrim(extraction_method)) > 0),
    CONSTRAINT job_skills_confidence_valid
        CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1)
);

CREATE TABLE IF NOT EXISTS skill_demand (
    skill_id BIGINT PRIMARY KEY
        REFERENCES skills (skill_id) ON DELETE CASCADE,
    job_count INTEGER NOT NULL DEFAULT 0,
    total_jobs INTEGER NOT NULL DEFAULT 0,
    demand_score NUMERIC(8, 7) NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT skill_demand_counts_nonnegative
        CHECK (job_count >= 0 AND total_jobs >= 0),
    CONSTRAINT skill_demand_count_within_total
        CHECK (job_count <= total_jobs),
    CONSTRAINT skill_demand_score_valid
        CHECK (demand_score BETWEEN 0 AND 1)
);

CREATE TABLE IF NOT EXISTS student_profiles (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    education_level TEXT,
    github_username TEXT,
    cv_storage_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT student_profiles_full_name_nonempty
        CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT student_profiles_email_nonempty
        CHECK (length(btrim(email)) > 0)
);

CREATE TABLE IF NOT EXISTS student_skills (
    user_id BIGINT NOT NULL
        REFERENCES student_profiles (user_id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL
        REFERENCES skills (skill_id) ON DELETE RESTRICT,
    proficiency_level SMALLINT NOT NULL,
    source TEXT NOT NULL,
    assessed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, skill_id, source),
    CONSTRAINT student_skills_proficiency_valid
        CHECK (proficiency_level BETWEEN 0 AND 5),
    CONSTRAINT student_skills_source_valid
        CHECK (source IN ('self_reported', 'resume', 'github', 'advisor'))
);

CREATE INDEX IF NOT EXISTS job_roles_role_vector_hnsw_idx
    ON job_roles USING hnsw (role_vector vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);

CREATE INDEX IF NOT EXISTS jobs_embedding_hnsw_idx
    ON jobs USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);

CREATE OR REPLACE FUNCTION refresh_skill_demand()
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    active_job_count INTEGER;
BEGIN
    SELECT count(*)::INTEGER
      INTO active_job_count
      FROM jobs
     WHERE expires_at IS NULL OR expires_at > now();

    INSERT INTO skill_demand (
        skill_id,
        job_count,
        total_jobs,
        demand_score,
        updated_at
    )
    SELECT
        s.skill_id,
        count(DISTINCT j.job_id)::INTEGER,
        active_job_count,
        CASE
            WHEN active_job_count = 0 THEN 0
            ELSE count(DISTINCT j.job_id)::NUMERIC / active_job_count
        END,
        now()
    FROM skills AS s
    LEFT JOIN job_skills AS js ON js.skill_id = s.skill_id
    LEFT JOIN jobs AS j
        ON j.job_id = js.job_id
       AND (j.expires_at IS NULL OR j.expires_at > now())
    GROUP BY s.skill_id
    ON CONFLICT (skill_id) DO UPDATE
       SET job_count = EXCLUDED.job_count,
           total_jobs = EXCLUDED.total_jobs,
           demand_score = EXCLUDED.demand_score,
           updated_at = EXCLUDED.updated_at;
END;
$$;

COMMIT;
